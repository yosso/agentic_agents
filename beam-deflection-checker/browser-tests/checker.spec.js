const { test, expect } = require('@playwright/test');
test('aluminum sections drive both solvers with editable geometry and principal axes', async ({ page }) => {
  await page.goto('/');
  await page.locator('#section-type').selectOption('ibeam');
  await expect(page.locator('[name=E]')).toHaveValue('10000');
  await expect(page.locator('[name=I]')).toHaveAttribute('readonly', '');
  await expect(page.locator('#awatif-status')).toHaveText('Methods agree');
  const strong = Number(await page.locator('[name=I]').inputValue());
  await page.locator('#section-axis').selectOption('iy');
  expect(Number(await page.locator('[name=I]').inputValue())).toBeLessThan(strong);
  await page.locator('#section-preset').selectOption('1');
  await expect(page.locator('#section-d')).toHaveValue('8');
  await page.locator('#section-d').fill('9');
  await expect(page.locator('#section-preset')).toHaveValue('custom');
  await page.locator('#section-tf').fill('5');
  await expect(page.locator('#error')).toContainText('I-beam needs');
  await expect(page.locator('#output')).toBeHidden();
  await page.locator('#section-type').selectOption('angle');
  await expect(page.locator('#angle-note')).toBeVisible();
  await expect(page.locator('#awatif-status')).toHaveText('Methods agree');
  const major = Number(await page.locator('[name=I]').inputValue());
  await page.locator('#section-axis').selectOption('minor');
  expect(Number(await page.locator('[name=I]').inputValue())).toBeLessThan(major);
  await page.locator('#section-t').fill('0');
  await expect(page.locator('#error')).toBeVisible();
  await page.locator('#section-t').fill('0.25');
  await expect(page.locator('#error')).toBeHidden();
  await page.locator('[name=E]').fill('10100');
  await expect(page.locator('#awatif-status')).toHaveText('Methods agree');
  await expect(page.locator('[name=E]')).toHaveValue('10100');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.locator('#section-type').selectOption('manual');
  await expect(page.locator('[name=I]')).toBeEditable();
  await page.getByRole('button', { name: 'Reset example' }).click();
  await expect(page.locator('[name=E]')).toHaveValue('29000');
  await expect(page.locator('[name=I]')).toHaveValue('500');
  await expect(page.locator('#awatif-deflection')).toHaveText('0.248 in');
});
test('Awatif comparison updates, invalidates, resets, and works on mobile', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.locator('#awatif-status')).toHaveText('Methods agree');
  await expect(page.locator('#awatif-deflection')).toHaveText('0.248 in');
  await expect(page.locator('#awatif-reactions')).toHaveText('10 kip / 10 kip');
  await expect(page.locator('#diagram circle')).toHaveCount(23);
  await page.locator('[name=P]').fill('10');
  await expect(page.locator('#awatif-deflection')).toHaveText('0.447 in');
  await page.locator('[name=w]').fill('10');
  await expect(page.locator('#awatif-limit')).toContainText('Exceeds limit');
  await expect(page.locator('#awatif-status')).toHaveText('Methods agree');
  await page.locator('[name=E]').fill('');
  await expect(page.locator('#error')).toBeVisible();
  await expect(page.locator('#output')).toBeHidden();
  await page.getByRole('button', { name: 'Reset example' }).click();
  await expect(page.locator('#awatif-deflection')).toHaveText('0.248 in');
  await page.locator('[name=w]').fill('0');
  await expect(page.locator('#awatif-deflection')).toHaveText('0 in');
  await expect(page.locator('#awatif-difference')).toContainText('zero-load reference');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
test('missing WASM reports unavailable without hiding formula results', async ({ page }) => {
  await page.route('**/*.wasm', route => route.abort());
  await page.goto('/');
  await expect(page.locator('#awatif-status')).toHaveText('Awatif check unavailable');
  await expect(page.locator('#awatif-results')).toBeHidden();
  await expect(page.locator('#deflection')).toHaveText('0.248 in');
});

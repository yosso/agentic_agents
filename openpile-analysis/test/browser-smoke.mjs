import { chromium } from '../../beam-deflection-checker/node_modules/playwright/index.mjs';
import { createApp } from '../server.mjs';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
const server=createApp();await new Promise(r=>server.listen(0,'127.0.0.1',r));
let browser;
try {
 browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1360,height:1000}});
 const errors=[];page.on('pageerror',e=>{errors.push(e.message);console.error(e.message);});
 await page.goto(`http://127.0.0.1:${server.address().port}`);
 await page.getByRole('button',{name:'Find default paths'}).click();
 await page.waitForFunction(()=>document.querySelector('#workbook').value.length>0);
 await page.getByRole('button',{name:'Load / review mapping'}).click();
 await page.waitForFunction(()=>document.querySelector('#mappingRows').rows.length>1);
 await page.getByRole('button',{name:'Load synthetic example'}).click();
 await page.waitForFunction(()=>document.querySelector('#source').textContent.includes('Synthetic'));
 if(!(await page.locator('#loadPreview').textContent()).includes('lateral FX'))throw Error('X-plane load preview missing');
 await page.locator('#plane').selectOption('Y');
 if(!(await page.locator('#loadPreview').textContent()).includes('lateral FY'))throw Error('Load preview did not follow plane selection');
 await page.locator('#plane').selectOption('X');
 await page.locator('#depth').fill('31');
 if(!(await page.locator('#batchFootings').textContent()).includes('start 31'))throw Error('Depth preview did not update');
 await page.getByRole('button',{name:'Validate selected case'}).click();
 await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('completed'),{},{timeout:30000}).catch(async e=>{throw Error(e.message+' '+await page.locator('#error').textContent());});
 await page.getByRole('button',{name:'Run selected case',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#metrics').children.length===3,{},{timeout:60000});
 const example=await (await page.request.get(`http://127.0.0.1:${server.address().port}/api/example`)).json();
 example.document.soil_profiles[0].layers[0].properties.model='PROJECT SOIL';
 const upload=()=>page.locator('#inputs').setInputFiles({name:'project.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(example.document))});
 await upload();
 await page.waitForFunction(()=>document.querySelector('#soils').value.includes('PROJECT SOIL'));
 let mappings=JSON.parse(await page.locator('#soils').inputValue());
 if(mappings['PROJECT SOIL']!==null || 'DEMO CLAY' in mappings)throw Error('Project labels must replace demo with unassigned entries');
 await page.getByLabel('PROJECT SOIL: OpenPile model',{exact:true}).selectOption('API_clay');
 mappings=JSON.parse(await page.locator('#soils').inputValue());
 if(mappings['PROJECT SOIL'].cohesion!=='cohesion_ultimate')throw Error('Clay controls did not generate mapping');
 await page.getByLabel('PROJECT SOIL: OpenPile model',{exact:true}).selectOption('API_sand');
 await page.getByLabel('PROJECT SOIL: Curve type',{exact:true}).selectOption('cyclic');
 mappings=JSON.parse(await page.locator('#soils').inputValue());
 if(mappings['PROJECT SOIL'].modulus!=='k_cyclic'||'cohesion' in mappings['PROJECT SOIL'])throw Error('Sand mapping contains incompatible fields');
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Download soil mappings',exact:true}).click();
 if((await downloadPromise).suggestedFilename()!=='soil-mappings.json')throw Error('Mapping download failed');
 example.settings.soil_models={'PROJECT SOIL':example.settings.soil_models['DEMO CLAY']};
 await page.locator('#import').setInputFiles({name:'settings.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(example.settings))});
 await page.waitForFunction(()=>JSON.parse(document.querySelector('#soils').value)['PROJECT SOIL']?.model==='API_clay');
 await upload();
 mappings=JSON.parse(await page.locator('#soils').inputValue());
 if(mappings['PROJECT SOIL'].model!=='API_clay')throw Error('Reload discarded reviewed mapping');
 await mkdir('openpile-analysis/results',{recursive:true});
 await page.screenshot({path:'openpile-analysis/results/browser.png',fullPage:true});
 if(errors.length)throw Error(errors.join('\n'));
 console.log('Browser smoke passed: example, depth preview, validation, solver, metrics.');
} finally {await browser?.close();await new Promise(r=>server.close(r));}
